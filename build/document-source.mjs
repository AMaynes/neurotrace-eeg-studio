/*
Purpose: Generates the repository map and declared type models from authored source files.
File Dependencies: build/source-standards.mjs, package.json.
*/


import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { sourceFiles } from './source-standards.mjs';

/** Assigns an owning subsystem without changing the framework's source locations. */
function subsystem(file) {
  if (!file.startsWith('app/')) return 'hosting';
  if (/directory|import-selection|event-keywords/.test(file)) return 'directory';
  if (/spectrogram/.test(file)) return 'spectral';
  if (/performance|resource-usage|recording-info|source-integrity|source-hash|scan-hash/.test(file)) return 'diagnostics';
  if (/annotation|recording-label|review-workspace|recovery|neurotrace-project|label-/.test(file)) return 'review';
  if (/eeg-core|file-window|mat73|mat-import|mat-event|raw-dat-mapping|bids-companions|local-recording/.test(file)) return 'recording';
  if (/page\.tsx|layout|tutorial|shortcut|workspace|session-tab|zoom-history|playback|window-amount|cursor-readout|timestamp/.test(file)) return 'workspace';
  return 'display';
}

/** Removes function bodies while retaining declared types, modifiers, and method signatures. */
function declaration(node, tree) {
  if (!ts.isClassDeclaration(node)) return node.getText(tree);
  const source = node.getText(tree), start = node.getStart(tree), edits = [];
  for (const member of node.members) {
    if (member.body) edits.push([member.body.getStart(tree) - start, member.body.end - start, ';']);
  }
  let text = source;
  for (const [first, end, replacement] of edits.sort((a, b) => b[0] - a[0])) text = text.slice(0, first) + replacement + text.slice(end);
  return text;
}

/** Extracts actual type declarations and their referenced type names from one source file. */
function typesIn(file, source) {
  const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true), types = [];
  /** Records declarations, including local types, without treating functions as classes. */
  function visit(node) {
    if ((ts.isClassDeclaration(node) || ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && node.name) {
      const references = new Set();
      /** Collects declared type references and inheritance clauses for the relationship graph. */
      function reference(child) {
        if (ts.isTypeReferenceNode(child)) references.add(child.typeName.getText(tree));
        if (ts.isExpressionWithTypeArguments(child)) references.add(child.expression.getText(tree));
        ts.forEachChild(child, reference);
      }
      reference(node);
      types.push({ name: node.name.text, file, kind: ts.isClassDeclaration(node) ? 'class' : ts.isInterfaceDeclaration(node) ? 'interface' : 'type', text: declaration(node, tree), references: [...references] });
    }
    ts.forEachChild(node, visit);
  }
  visit(tree);
  return types;
}

/** Produces deterministic Markdown inventories and checks them without writing when requested. */
function main() {
  const files = sourceFiles(), groups = new Map(), outputs = new Map();
  let structure = '# Repository map\n\nGenerated by `npm run docs:generate`. Commands and standards live in [README](README.md); contracts live in the [technical reference](docs/PROJECT_DOC.md). `app/` is the framework entry directory.\n\n| File | Responsibility |\n| --- | --- |\n';
  for (const file of files.sort()) {
    const source = fs.readFileSync(file, 'utf8');
    const purpose = source.match(/Purpose: ([\s\S]*?)\n(?:# )?File Dependencies:/)?.[1].replace(/\s+/g, ' ').trim() ?? 'See source header.';
    structure += `| [${file}](${file.replaceAll(' ', '%20')}) | ${purpose.replaceAll('|', '\\|')} |\n`;
    if (/^(app|worker|db)\/.+\.(ts|tsx)$/.test(file) || file === 'cloudflare-env.d.ts') {
      const name = subsystem(file);
      groups.set(name, [...(groups.get(name) ?? []), ...typesIn(file, source)]);
    }
  }
  structure += '\n## Non-source files\n\n- `package.json` and lockfile: commands and exact dependency graph.\n- `tsconfig.json`, hosting/build metadata, and workflow: environment contracts.\n- `public/`: static assets.\n- `docs/`: contracts, models, screenshots, and cleanup evidence.\n- `work/`, `outputs/`, `node_modules/`, `dist/`, `pages-dist/`, and provider caches: ignored local/generated content.\n';
  outputs.set('STRUCTURE.md', structure);
  let index = '# Declared type models\n\nGenerated from the current source by `npm run docs:generate`; `npm run docs:check` detects stale inventories. The [architecture overview](../PROJECT_DOC.md#architecture-and-classobject-model) connects the subsystems.\n\nGraphs show declared type dependencies, not inferred object ownership. Exact declarations below each graph retain fields, visibility, method signatures, inheritance, and unions; method bodies are omitted. Unannotated members retain their source inference rather than an invented type. Imported/browser/library boundaries remain source references.\n\n| Subsystem | Declarations |\n| --- | --- |\n';
  for (const [group, types] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    index += `| [${group}](${group}.md) | ${types.length} |\n`;
    let doc = `# ${group[0].toUpperCase() + group.slice(1)} type model\n\n[All models](README.md) · [Feature contracts](../PROJECT_DOC.md)\n\n`;
    // Split large graphs into bounded panels; declarations remain complete below.
    for (let first = 0; first < types.length; first += 12) {
      const panel = types.slice(first, first + 12);
      doc += '```mermaid\nclassDiagram\n';
      for (let i = 0; i < panel.length; i++) {
        doc += `  class T${i}["${panel[i].name}"]\n`;
        if (panel[i].kind !== 'class') doc += `  <<${panel[i].kind}>> T${i}\n`;
      }
      for (let i = 0; i < panel.length; i++) for (let j = 0; j < panel.length; j++) if (i !== j && panel[i].references.includes(panel[j].name)) doc += `  T${i} ..> T${j} : type reference\n`;
      doc += '```\n\n';
    }
    for (const item of types) doc += `## ${item.name}\n\nSource: [${item.file}](../../${item.file}). Kind: ${item.kind}.\n\n\x60\x60\x60typescript\n${item.text}\n\x60\x60\x60\n\n`;
    outputs.set(`docs/models/${group}.md`, `${doc.trimEnd()}\n`);
  }
  outputs.set('docs/models/README.md', index);
  const stale = [];
  for (const [file, text] of outputs) {
    if (process.argv.includes('--check')) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text.replace(/\r\n/g, '\n')) stale.push(file); }
    else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); }
  }
  if (stale.length) { console.error(`Stale documentation: ${stale.join(', ')}`); process.exitCode = 1; }
  else console.log(`${outputs.size} source/type inventories ${process.argv.includes('--check') ? 'verified' : 'written'}.`);
}

main();
